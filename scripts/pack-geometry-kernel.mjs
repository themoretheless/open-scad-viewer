import {brotliCompressSync, constants} from 'node:zlib'
import {writeFileSync} from 'node:fs'
import {resolve} from 'node:path'
import {encodeVariableBase108} from './wasm-base91.mjs'
import {wasmArtifactIdentityModule} from './wasm-artifact-identity.mjs'
import {packStampHit,writePackStamp} from './wasm-pack-stamp.mjs'

// Separate packing from compilation so an existing optimized artifact can be
// repackaged without changing its byte identity or re-running wasm-opt.
export function packGeometryKernel(wasm, output, publicWasm) {
const stampPath=resolve(output,'.wasm-pack-stamp-brotli24-16-font-sections-v1-base108v')
const packOutputs=[resolve(output,'kernel_bg.wasm'),resolve(publicWasm,'geometry-kernel.wasm'),resolve(output,'identity.ts'),resolve(output,'bytes.ts')]
if(packStampHit(stampPath,wasm,packOutputs)){
  console.log('geometry-kernels: wasm unchanged, skipping packaging (stamp hit)')
}else{
if(wasm.length>16*1024*1024)throw new Error('Geometry WASM exceeds decompression output limit')
const module=new WebAssembly.Module(wasm)
if(WebAssembly.Module.imports(module).length)throw new Error('Geometry WASM must not import external functions')
// A separate bounded synchronous decoder preserves the public host call contract.
// Separate code from following data without changing decoded WASM identity.
let at=8, split=wasm.length
while(at<wasm.length){
  const id=wasm[at++];let length=0,shift=0,byte
  do { if(at>=wasm.length||shift>28)throw new Error('Invalid WASM section length');byte=wasm[at++];length+=(byte&127)*2**shift;shift+=7 } while(byte&128)
  at+=length
  if(at>wasm.length)throw new Error('Truncated WASM section')
  if(id===10)split=at
}
const chunks=split<wasm.length?[wasm.subarray(0,split),wasm.subarray(split)]:[wasm]
const compressed=chunks.map(chunk=>brotliCompressSync(chunk,{params:{[constants.BROTLI_PARAM_QUALITY]:11,[constants.BROTLI_PARAM_LGWIN]:24,[constants.BROTLI_PARAM_LGBLOCK]:16,[constants.BROTLI_PARAM_MODE]:constants.BROTLI_MODE_FONT}}))
const header=Buffer.alloc(5+8*chunks.length)
header.writeUInt32LE(wasm.length+0x80000000);header[4]=chunks.length
chunks.forEach((chunk,i)=>{header.writeUInt32LE(chunk.length,5+8*i);header.writeUInt32LE(compressed[i].length,9+8*i)})
const packed=Buffer.concat([header,...compressed])
if(packed.length-4>4*1024*1024)throw new Error('Geometry WASM exceeds compressed input limit')
const bytes=encodeVariableBase108(packed)
// Prepare the complete package before publishing: compression or size failures
// must preserve the previously installed kernel, fingerprint and embedded bytes.
// This also avoids a compression-length window with a new identity and old bytes.
writeFileSync(resolve(output,'kernel_bg.wasm'),wasm)
writeFileSync(resolve(publicWasm,'geometry-kernel.wasm'),wasm)
writeFileSync(resolve(output,'bytes.ts'),`// Generated by build-geometry-kernels.mjs; do not edit.\nexport default '${bytes}'\n`)
writeFileSync(resolve(output,'identity.ts'),wasmArtifactIdentityModule(wasm))
writePackStamp(stampPath,wasm)
}

}
