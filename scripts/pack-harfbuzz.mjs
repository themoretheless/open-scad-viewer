import {brotliCompressSync, brotliDecompressSync, constants} from 'node:zlib'
import {mkdirSync, readFileSync, writeFileSync} from 'node:fs'
import {createRequire} from 'node:module'

// Transport packaging only: preserve every byte of the installed shaping runtime.
const require = createRequire(import.meta.url)
const wasm = readFileSync(require.resolve('harfbuzzjs/hb.wasm'))
new WebAssembly.Module(wasm)
if (wasm.length > 16 * 1024 * 1024) throw new Error('HarfBuzz WASM exceeds decompression output limit')
const compressed = brotliCompressSync(wasm, {params: {[constants.BROTLI_PARAM_QUALITY]: 11}})
if (compressed.length > 4 * 1024 * 1024) throw new Error('HarfBuzz WASM exceeds compressed input limit')
if (!brotliDecompressSync(compressed).equals(wasm)) throw new Error('HarfBuzz packaging changed WASM bytes')
const size = Buffer.alloc(4)
size.writeUInt32LE(wasm.length)
const output = new URL('../src/generated/harfbuzz/', import.meta.url)
mkdirSync(output, {recursive: true})
writeFileSync(new URL('bytes.ts', output), `// Generated by pack-harfbuzz.mjs; do not edit.\nexport default '${Buffer.concat([size, compressed]).toString('base64')}'\n`)
