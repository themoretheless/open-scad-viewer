import {deflateRawSync} from 'node:zlib'
import {spawnSync} from 'node:child_process'
import {mkdirSync, readFileSync, writeFileSync} from 'node:fs'
import {resolve} from 'node:path'
import {packStampHit, writePackStamp} from './wasm-pack-stamp.mjs'

/** Build a compression-only bootstrap; it has no geometry dependencies. */
export function buildWasmBrotli(root, cargoTarget) {
  const result = spawnSync('cargo', ['build', '--locked', '--release', '--config', 'profile.release.strip="symbols"', '--config', 'profile.release.codegen-units=1', '--config', 'profile.release.panic="abort"', '--target', 'wasm32-unknown-unknown', '--manifest-path', 'crates/wasm-brotli/Cargo.toml'], {
    cwd: root, stdio: 'inherit', env: {...process.env, CARGO_TARGET_DIR: cargoTarget},
  })
  if (result.error) throw result.error
  if (result.status !== 0) throw new Error(`Brotli decoder build failed (${result.status})`)
  const wasm = readFileSync(resolve(cargoTarget, 'wasm32-unknown-unknown/release/wasm_brotli.wasm'))
  const output = resolve(root, 'src/generated/wasm-brotli')
  mkdirSync(output, {recursive: true})
  // build-geometry-kernels.mjs and build-photogrammetry.mjs both call this in
  // one `build:geometry` run; the stamp makes the repeat call cheap.
  const stampPath = resolve(output, '.wasm-pack-stamp')
  if (packStampHit(stampPath, wasm, [resolve(output, 'bytes.ts')])) {
    console.log('wasm-brotli: wasm unchanged, skipping packaging (stamp hit)')
    return
  }
  if (WebAssembly.Module.imports(new WebAssembly.Module(wasm)).length) throw new Error('Brotli WASM must not import external functions')
  const size = Buffer.alloc(4)
  size.writeUInt32LE(wasm.length)
  const bytes = Buffer.concat([size, deflateRawSync(wasm, {level: 9})]).toString('base64')
  writeFileSync(resolve(output, 'bytes.ts'), `// Generated by build-wasm-brotli.mjs; do not edit.\nexport default '${bytes}'\n`)
  writePackStamp(stampPath, wasm)
}
