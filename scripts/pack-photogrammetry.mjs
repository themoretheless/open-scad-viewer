import {encodeVariableBase118} from './wasm-base91.mjs'
import {brotliCompressSync, constants} from 'node:zlib'
import {writeFileSync} from 'node:fs'
import {resolve} from 'node:path'
import {packStampHit,writePackStamp} from './wasm-pack-stamp.mjs'

export function packPhotogrammetry(bytes, folder, publicWasm) {
const stampPath=resolve(folder,'.wasm-pack-stamp-base118v')
if(packStampHit(stampPath,bytes,[resolve(folder,'bytes.ts'),resolve(publicWasm,'photogrammetry.wasm')])){
  console.log('photogrammetry: wasm unchanged, skipping packaging (stamp hit)')
}else{
if(WebAssembly.Module.imports(new WebAssembly.Module(bytes)).length)throw new Error('Photogrammetry WASM must not import external functions')
if(bytes.length>16*1024*1024)throw new Error('Photogrammetry WASM exceeds decompression output limit')
const compressed=brotliCompressSync(bytes,{params:{[constants.BROTLI_PARAM_QUALITY]:11}})
if(compressed.length>4*1024*1024)throw new Error('Photogrammetry WASM exceeds compressed input limit')
const size=Buffer.alloc(4);size.writeUInt32LE(bytes.length)
writeFileSync(resolve(folder,'bytes.ts'),`// Generated by build-photogrammetry.mjs.\nexport default '${encodeVariableBase118(Buffer.concat([size,compressed]))}'\n`)
writeFileSync(resolve(publicWasm,'photogrammetry.wasm'),bytes)
writePackStamp(stampPath,bytes)
}

}
