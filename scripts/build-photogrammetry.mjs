import {brotliCompressSync, constants} from 'node:zlib'
import {spawnSync} from 'node:child_process'
import {mkdirSync,readFileSync,writeFileSync} from 'node:fs'
import {fileURLToPath} from 'node:url'
import {resolve} from 'node:path'
import {buildWasmBrotli} from './build-wasm-brotli.mjs'
const root=fileURLToPath(new URL('../',import.meta.url))
const cargoTarget=resolve(root,'crates/target')
buildWasmBrotli(root,cargoTarget)
const result=spawnSync('cargo',['build','--locked','--release','--target','wasm32-unknown-unknown','--manifest-path','crates/photogrammetry-wasm/Cargo.toml'],{cwd:root,stdio:'inherit',env:{...process.env,CARGO_TARGET_DIR:cargoTarget}})
if(result.error)throw result.error
if(result.status!==0)process.exit(result.status??1)
const bytes=readFileSync(resolve(root,'crates/target/wasm32-unknown-unknown/release/photogrammetry_wasm.wasm'))
if(WebAssembly.Module.imports(new WebAssembly.Module(bytes)).length)throw new Error('Photogrammetry WASM must not import external functions')
const folder=resolve(root,'src/generated/photogrammetry');mkdirSync(folder,{recursive:true})
const publicWasm=resolve(root,'public/wasm');mkdirSync(publicWasm,{recursive:true})
if(bytes.length>16*1024*1024)throw new Error('Photogrammetry WASM exceeds decompression output limit')
const compressed=brotliCompressSync(bytes,{params:{[constants.BROTLI_PARAM_QUALITY]:11}})
if(compressed.length>4*1024*1024)throw new Error('Photogrammetry WASM exceeds compressed input limit')
const size=Buffer.alloc(4);size.writeUInt32LE(bytes.length)
writeFileSync(resolve(folder,'bytes.ts'),`// Generated by build-photogrammetry.mjs.\nexport default '${Buffer.concat([size,compressed]).toString('base64')}'\n`)
writeFileSync(resolve(publicWasm,'photogrammetry.wasm'),bytes)
