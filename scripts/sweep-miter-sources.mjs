export async function selectSweepMiterSources({ bodyBoundaryMode, surfaceMode, lawMatrixMode, sourceDirectory, filter }) {
  const inventory = lawMatrixMode
    ? (await readdir(sourceDirectory)).filter(file => /^miter-laws-(open|closed)-[a-z-]+\.r$/.test(file)).sort()
    : bodyBoundaryMode ? bodyBoundarySources : surfaceMode ? surfaceSources : miterSources
  const selected = inventory.filter(file => !filter || file === filter)
  if (lawMatrixMode && !filter) {
    const expected = [false, true].flatMap(closed => Array.from({length: 8}, (_, bits) => {
      const laws = [bits & 1 ? 'affine' : null, bits & 2 ? 'authored' : null, bits & 4 ? 'guide' : null]
        .filter(Boolean).join('-') || 'plain'
      return `miter-laws-${closed ? 'closed' : 'open'}-${laws}.r`
    })).sort()
    assert.deepEqual(selected, expected,
      'Complete law matrix requires each open/closed affine/authored/guide combination exactly once')
  }
  assert.ok(selected.length, 'Unknown mode filter')
  return selected
}
