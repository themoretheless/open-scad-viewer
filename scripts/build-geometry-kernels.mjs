import { spawnSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { resolve } from 'node:path'
import ts from 'typescript'
import { gzipSync } from 'node:zlib'
const root = fileURLToPath(new URL('../', import.meta.url))
const output = resolve(root, 'src/generated/geometry-kernels')
function run(command, args) {
  const result = spawnSync(command, args, { cwd: root, stdio: 'inherit' })
  if (result.error) throw result.error
  if (result.status !== 0) process.exit(result.status ?? 1)
}
run('cargo', ['build', '--locked', '--release', '--target', 'wasm32-unknown-unknown', '--manifest-path', 'crates/geometry-bridge/Cargo.toml'])
mkdirSync(output, { recursive: true })
run('wasm-bindgen', ['crates/target/wasm32-unknown-unknown/release/geometry_bridge.wasm', '--target', 'web', '--out-dir', output, '--out-name', 'kernel'])
// Keep only synchronous initialization. The standard web target also emits
// an unused fetch loader, which must not enter the isolated worker closure.
const bindingPath = resolve(output, 'kernel.js')
const binding = readFileSync(bindingPath, 'utf8')
const ast = ts.createSourceFile('kernel.js', binding, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS)
const removed = new Set()
const syncBinding = ast.statements.map(statement => {
  if (ts.isFunctionDeclaration(statement) && ['__wbg_load', '__wbg_init'].includes(statement.name?.text)) {
    removed.add(statement.name.text)
    return ''
  }
  if (ts.isExportDeclaration(statement) && statement.exportClause && ts.isNamedExports(statement.exportClause)
    && statement.exportClause.elements.some(item => item.propertyName?.text === '__wbg_init')) {
    return '\nexport { initSync };\n'
  }
  return binding.slice(statement.getFullStart(), statement.end)
}).join('')
if (removed.size !== 2 || /\bfetch\s*\(/.test(syncBinding)) throw new Error('Unexpected wasm-bindgen loader layout')
writeFileSync(bindingPath, syncBinding + '\n')
// Compressed embedded bytes preserve the existing synchronous API in browser workers and
// Node, without top-level await, filesystem imports or a network-time fallback.
const bytes = gzipSync(readFileSync(resolve(output, 'kernel_bg.wasm')), { level: 9 }).toString('base64')
writeFileSync(resolve(output, 'bytes.ts'), `// Generated by build-geometry-kernels.mjs; do not edit.\nexport default '${bytes}'\n`)
