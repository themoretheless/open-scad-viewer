use super::J;

// Keep reachability and text graph selection on the same reference contract.
pub(super) fn has_trim_loops(node: &J) -> bool {
    let operation = node["op"].as_str().unwrap_or("");
    matches!(
        operation,
        "brep_extrude_curves"
            | "brep_miter_sweep"
            | "brep_progressive_miter_sweep"
            | "brep_progressive_sweep"
            | "sew_periodic_source_face"
    ) || (node.get("loops").is_some()
        && matches!(
            operation,
            "affine_trim_piece"
                | "affine_trim_surface"
                | "arrange_section_caps"
                | "assemble_section_material"
                | "bound_boundary_section"
                | "bound_principal_face_directions"
                | "bound_principal_face_moments"
                | "bound_wire_moments"
                | "bound_world_face_mass"
                | "bounded_section_brep_sheets"
                | "build_material_segments"
                | "build_plane_section_segments"
                | "cap_section_holes"
                | "cap_section_wire"
                | "cast_trimmed_face_ray"
                | "certified_profile_edit"
                | "classify_face_section"
                | "classify_section_gaps"
                | "clip_plane_section"
                | "coplanar_ray_contacts"
                | "coplanar_ray_partition"
                | "curve_trimmed_face_distance"
                | "enclose_face_events"
                | "exact_wire_inertia"
                | "exact_wire_mass"
                | "expanded_section_sheets"
                | "lift_planar_wire"
                | "match_quadratic_contacts"
                | "material_segment_curve"
                | "measure_section_material"
                | "optimize_section_edge"
                | "partition_face_events"
                | "planar_boundary_distance"
                | "planar_face_perimeter"
                | "planar_material_distance"
                | "principal_face_directions"
                | "principal_face_moments"
                | "project_planar_wire"
                | "reclock_trim_piece"
                | "reclock_trim_surface"
                | "refine_boundary_section"
                | "relayout_trim_piece"
                | "relayout_trim_surface"
                | "remap_trim_piece"
                | "remap_trim_surface"
                | "resolve_boundary_section"
                | "section_brep_sheets"
                | "shared_boundary_contacts"
                | "shared_boundary_spans"
                | "signed_planar_face_area"
                | "store_section_edge"
                | "store_section_edges"
                | "swept_ball_face_clearance"
                | "transpose_trim_piece"
                | "transpose_trim_surface"
                | "trimmed_face_clearance"
                | "trimmed_surface_area_in_window"
                | "trimmed_surface_area_inertia"
                | "trimmed_surface_centroid"
                | "uv_loop_closure"
                | "uv_loop_simplicity"
                | "uv_trim_location"
                | "world_face_mass"
        ))
}
