/** Translate key for the active language, falling back to English, then the key itself. */
export const t = (k: string) => L[lang.value]?.[k] ?? L.en?.[k] ?? k

export const toggleLang = () => {
  const idx = LANGS.indexOf(lang.value)
  lang.value = LANGS[(idx + 1) % LANGS.length]
  storageSet('scad-lang', lang.value)
}
